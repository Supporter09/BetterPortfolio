export type PixelIconName = keyof typeof BITMAPS;
export const PIXEL_ICON_NAMES = Object.keys(BITMAPS) as PixelIconName[];

interface Run {
  x: number;
  y: number;
  w: number;
}

/** Horizontal run-length pass: one <rect> per lit span instead of one per cell. */
function runsOf(rows: readonly string[]): Run[] {
  const runs: Run[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      const start = x;
      while (x < row.length && row[x] === '#') x++;
      runs.push({ x: start, y, w: x - start });
    }
  });
  return runs;
}

const RUNS = Object.fromEntries(
  PIXEL_ICON_NAMES.map((name) => [name, runsOf(BITMAPS[name])]),
) as Record<PixelIconName, Run[]>;

export interface PixelIconProps extends Omit<SVGProps<SVGSVGElement>, 'width' | 'height' | 'name'> {
  name: PixelIconName;
  /** Rendered box in CSS px (grid is 12×12; 16/20/24 keep whole-pixel cells at 1×/1.25×/1.5× scale nearest). */
  size?: 16 | 20 | 24 | 32 | 48;
  /** Meaningful icon: rendered with a <title> and role="img" instead of aria-hidden. */
  title?: string;
}

/**
 * PixelIcon: bitmap glyph as crisp SVG <rect>s (`shape-rendering: crispEdges`, `fill: currentColor`).
 * Decorative by default (`aria-hidden`); pass `title` for a meaningful icon.
 */
export function PixelIcon({ name, size = 16, title, className, ...rest }: PixelIconProps) {
  const grid = BITMAPS[name].length;
  return (
    <svg
      viewBox={`0 0 ${grid} ${grid}`}
      width={size}
      height={size}
      shapeRendering="crispEdges"
      fill="currentColor"
      className={cn('inline-block shrink-0 align-middle', className)}
      aria-hidden={title ? undefined : 'true'}
      role={title ? 'img' : undefined}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      {RUNS[name].map((run) => (
        <rect key={`${run.y}-${run.x}`} x={run.x} y={run.y} width={run.w} height={1} />
      ))}
    </svg>
  );
}
